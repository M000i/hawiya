'use strict';

/*
 * THIRD_PARTY_NOTICES.md from library/sources.json and library/licenses.json (task 3.2, R-064).
 *
 *   npm run notices                                   writes THIRD_PARTY_NOTICES.md
 *   node tools/notices.js --library <dir> --out <file>
 *
 * Every third-party source is listed (the project's own entry, "own": true, is not third-party: its license is
 * LICENSE) with its repository, license, the date its license file was read, what is used, and its copyright lines;
 * a source with parts under a second license ("also", e.g. Lucide icons derived from Feather) lists those too. Then
 * the full text of every license used, once each. Same files -> same bytes (no clock). `npm run check` fails when
 * the committed file differs from what this renders.
 */

const fs = require('node:fs');
const path = require('node:path');
const build = require('./build.js');
const validate = require('../picker/js/core/validate.js');
const SCHEMAS = require('../picker/js/core/schemas.js');

const ROOT = path.join(__dirname, '..');

class NoticesError extends Error {}

// The project's own entry in sources.json: its license is LICENSE, so it is not a third-party notice.
const OWN_ID = 'hawiya';

// The shapes of sources.json and licenses.json (npm run check reports every error; render needs them).
const T = SCHEMAS.template;
const HTTPS = T.properties.source.properties.url;
const SPDX = T.properties.source.properties.license;
const LINES = { type: 'array', minItems: 1, items: { type: 'string', minLength: 1, maxLength: 300 } };
const checkSources = validate.compile({
  type: 'array',
  minItems: 1,
  items: {
    type: 'object',
    additionalProperties: false,
    required: ['id', 'name', 'url', 'license', 'licenseFile', 'licenseReadAt', 'copyright', 'use'],
    properties: {
      id: T.$defs.id,
      name: T.properties.source.properties.name,
      own: { const: true },
      url: HTTPS,
      license: SPDX,
      licenseFile: HTTPS,
      licenseReadAt: { type: 'string', pattern: '^\\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\\d|3[01])$' },
      copyright: LINES,
      use: { type: 'string', minLength: 1, maxLength: 300 },
      note: { type: 'string', minLength: 1, maxLength: 500 },
      // The font families this source provides (task 5.1): npm run check needs every font a template names here.
      fonts: {
        type: 'array',
        minItems: 1,
        uniqueItems: true,
        items: { type: 'string', minLength: 1, maxLength: 100 }
      },
      also: {
        type: 'array',
        minItems: 1,
        items: {
          type: 'object',
          additionalProperties: false,
          required: ['license', 'copyright', 'for'],
          properties: { license: SPDX, copyright: LINES, for: { type: 'string', minLength: 1, maxLength: 300 } }
        }
      }
    }
  }
});
const checkLicenses = validate.compile({
  type: 'object',
  additionalProperties: false,
  required: ['allowed', 'forbiddenSources'],
  properties: {
    allowed: {
      type: 'array',
      minItems: 1,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'name'],
        properties: {
          id: SPDX,
          name: { type: 'string', minLength: 1, maxLength: 100 },
          note: { type: 'string', minLength: 1, maxLength: 300 },
          text: { type: 'array', minItems: 1, items: { type: 'string', maxLength: 200 } }
        }
      }
    },
    forbiddenSources: {
      type: 'array',
      minItems: 1,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['name', 'reason', 'match'],
        properties: {
          name: { type: 'string', minLength: 1, maxLength: 100 },
          reason: { type: 'string', minLength: 1, maxLength: 300 },
          match: { type: 'array', minItems: 1, items: { type: 'string', minLength: 3, maxLength: 60 } },
          ids: { type: 'array', minItems: 1, items: { type: 'string', minLength: 1, maxLength: 60 } }
        }
      }
    }
  }
});

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ');
const fence = (lines) => ['```text', ...lines, '```'];

function render(sources, licenses) {
  const byId = new Map(licenses.allowed.map((l) => [l.id, l]));
  const license = (id, where) => {
    const l = byId.get(id);
    if (!l) throw new NoticesError(`${where}: license "${id}" is not in the allowed list`);
    if (!Array.isArray(l.text) || !l.text.length)
      throw new NoticesError(`${where}: license "${id}" has no text in licenses.json`);
    return l;
  };
  const third = sources.filter((s) => !(s.own && s.id === OWN_ID));
  const used = new Set();
  for (const s of third) {
    used.add(license(s.license, s.name).id);
    for (const a of s.also || []) used.add(license(a.license, `${s.name} (also)`).id);
  }

  const out = [
    '<!-- GENERATED by tools/notices.js from library/sources.json and library/licenses.json.',
    '     Do not edit: change those files and run `npm run notices`. -->',
    '',
    '# Third-party notices',
    '',
    'إشعارات المصادر الخارجية: كل مصدر خارجي تستخدمه Hawiya أو تذكره، مع رخصته وأصحاب حقوقه، ثم نص كل رخصة كاملًا.',
    '',
    'Hawiya is under the MIT License (see `LICENSE`). It uses or names the third-party sources below; each keeps its',
    'own license. The full text of every license follows the list.',
    '',
    '| Source | License | Used for |',
    '|---|---|---|'
  ];
  for (const s of third) {
    const also = (s.also || []).map((a) => ` + ${a.license}`).join('');
    out.push(`| [${cell(s.name)}](${s.url}) | ${s.license}${also} | ${cell(s.use)} |`);
  }
  for (const s of third) {
    const l = byId.get(s.license);
    out.push('', `## ${s.name}`, '');
    out.push(`- Repository: ${s.url}`);
    out.push(`- License: ${l.name} (\`${l.id}\`), read from ${s.licenseFile} on ${s.licenseReadAt}`);
    out.push(`- Used for: ${s.use}`);
    if (s.note) out.push(`- Note: ${s.note}`);
    out.push('', ...fence(s.copyright));
    for (const a of s.also || []) {
      const la = byId.get(a.license);
      out.push('', `Also under the ${la.name} (\`${la.id}\`): ${a.for}`, '', ...fence(a.copyright));
    }
  }
  out.push('', '## License texts');
  for (const l of licenses.allowed) {
    if (!used.has(l.id)) continue;
    out.push('', `### ${l.name} (\`${l.id}\`)`, '');
    if (l.note) out.push(l.note, '');
    out.push(...fence(l.text));
  }
  return out.join('\n') + '\n';
}

// Reads both files of a library folder; throws NoticesError with the problems (shape is checked by npm run check).
function load(libraryDir) {
  const problems = [];
  const sources = build.readJson(path.join(libraryDir, 'sources.json'), problems);
  const licenses = build.readJson(path.join(libraryDir, 'licenses.json'), problems);
  if (problems.length) throw new NoticesError(problems.join('; '));
  const bad = [
    ['sources.json', checkSources(sources)],
    ['licenses.json', checkLicenses(licenses)]
  ].filter(([, r]) => !r.valid);
  if (bad.length) {
    const first = bad.map(([f, r]) => `${f}${r.errors[0].instancePath || '/'} ${r.errors[0].message}`);
    throw new NoticesError(`${first.join('; ')} (npm run check lists every problem)`);
  }
  return { sources, licenses };
}

function main(argv) {
  const opts = { libraryDir: path.join(ROOT, 'library'), out: path.join(ROOT, 'THIRD_PARTY_NOTICES.md') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if ((a === '--library' || a === '--out') && argv[i + 1])
      opts[a === '--library' ? 'libraryDir' : 'out'] = path.resolve(argv[++i]);
    else {
      process.stderr.write(
        `hawiya notices: unknown option ${a}\nusage: node tools/notices.js [--library <dir>] [--out <file>]\n`
      );
      return 2;
    }
  }
  try {
    const { sources, licenses } = load(opts.libraryDir);
    const text = render(sources, licenses);
    const tmp = `${opts.out}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, text, { flag: 'wx' });
    fs.renameSync(tmp, opts.out);
    process.stdout.write(
      `hawiya notices: wrote ${path.relative(process.cwd(), opts.out) || opts.out} (${sources.filter((s) => !s.own).length} sources)\n`
    );
    return 0;
  } catch (e) {
    if (!(e instanceof NoticesError)) throw e;
    process.stderr.write(`hawiya notices: ${e.message}; nothing was written\n`);
    return 1;
  }
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { render, load, main, NoticesError, OWN_ID, checkSources, checkLicenses };
