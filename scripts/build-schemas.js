'use strict';

/*
 * Writes picker/js/core/schemas.js: the three schemas in schema/*.json as one script the picker page can load
 * from file:// (no fetch). schema/*.json stays the only source; tests/validate.test.js fails when the copy is stale.
 *
 *   node scripts/build-schemas.js           write the file
 *   node scripts/build-schemas.js --check   exit 1 if the file is missing or out of date
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'picker', 'js', 'core', 'schemas.js');
const NAMES = ['identity', 'template', 'session'];

function render() {
  const data = {};
  for (const n of NAMES) data[n] = JSON.parse(fs.readFileSync(path.join(ROOT, 'schema', `${n}.schema.json`), 'utf8'));
  // JSON.stringify escapes nothing a script can misread except U+2028/U+2029 (fine in ES2019+) — escape them anyway.
  const LS = String.fromCharCode(0x2028);
  const PS = String.fromCharCode(0x2029);
  const json = JSON.stringify(data, null, 2).split(LS).join('\\u2028').split(PS).join('\\u2029');
  return (
    '/* GENERATED by scripts/build-schemas.js from schema/*.json. Do not edit: change the schema and run\n' +
    '   `node scripts/build-schemas.js`. Browser: window.Hawiya.schemas (load before validate.js); Node: require. */\n' +
    '(function (root, data) {\n' +
    '  (function freeze(o) {\n' +
    '    Object.freeze(o);\n' +
    '    Object.keys(o).forEach(function (k) {\n' +
    "      if (o[k] && typeof o[k] === 'object') freeze(o[k]);\n" +
    '    });\n' +
    '  })(data); // read-only: nothing can loosen a rule at run time\n' +
    "  if (typeof module === 'object' && module && module.exports && typeof require === 'function') {\n" +
    '    module.exports = data;\n' +
    '  } else {\n' +
    '    root.Hawiya = root.Hawiya || {};\n' +
    '    root.Hawiya.schemas = data;\n' +
    '  }\n' +
    "})(typeof self !== 'undefined' ? self : this, " +
    json +
    ');\n'
  );
}

if (require.main === module) {
  const want = render();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== want) {
      console.error('picker/js/core/schemas.js is out of date: run node scripts/build-schemas.js');
      process.exit(1);
    }
    console.log('schemas.js is up to date');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote picker/js/core/schemas.js');
  }
}

module.exports = { render, OUT };
